"""
Uploads the simulated sessions (simulation_output/) to Supabase, keeping their original timestamps,
and records the ML runs from the 100-session checkpoints as if they had run at those times.

IDs are generated by the DB; every inserted ID is saved to simulation_output/upload_manifest.json
so the upload can be rolled back with:  py -3 upload_simulation.py --rollback

Usage:
    py -3 upload_simulation.py [--dir simulation_output] [--dry-run]
"""
import os
import json
import argparse
from datetime import timedelta

import pandas as pd
from dotenv import load_dotenv
from supabase import create_client

PROJECT_DIR = os.path.dirname(os.path.abspath(__file__))
load_dotenv(os.path.join(PROJECT_DIR, ".env"))
CHUNK = 500


def load(dir_path, name):
    with open(os.path.join(dir_path, f"{name}.json"), encoding="utf-8") as f:
        return json.load(f)


def insert_one(client, table, row, pk):
    return client.table(table).insert(row).execute().data[0][pk]


def insert_many(client, table, rows, pk):
    ids = []
    for i in range(0, len(rows), CHUNK):
        ids += [r[pk] for r in client.table(table).insert(rows[i:i + CHUNK]).execute().data]
    return ids


def checkpoint_run_rows(dir_path):
    """Best-model row per checkpoint, timestamped shortly after the checkpoint's last labeled session."""
    import analytics_pipeline_final as ml

    runs = load(os.path.join(dir_path, "analytics_outputs"), "checkpoint_runs")
    df = pd.DataFrame(load(dir_path, "generated_schedules"))
    labeled = ml.session_label_table(df)
    labeled = labeled[labeled["is_labeled"]].reset_index(drop=True)

    rows = []
    for i, run in enumerate(runs):
        best = next(m for m in run["models"] if m["model"] == run["best_model"])
        w = run["best_weights"]
        run_time = labeled.iloc[run["checkpoint"] - 1]["created_at"] + timedelta(minutes=7)
        rows.append({
            "model_name": run["best_model"],
            "weight_g": w["G"], "weight_d": w["D"], "weight_ld": w["LD"], "weight_t": w["T"],
            "weight_lw": w["LW"], "weight_c": w["C"], "weight_a": w["A"],
            "num_training_records": run["num_training_records"],
            "accuracy": best["accuracy"], "precision": best["precision"], "recall": best["recall"],
            "f1_score": best["f1"], "auc": best["auc"],
            "semi_supervised_used": run["semi_supervised_used"],
            "is_best_run": i == len(runs) - 1,
            "created_at": run_time.isoformat(),
        })
    return rows


def upload(client, dir_path, dry_run):
    sessions = sorted(load(dir_path, "chat_sessions"), key=lambda r: r["created_at"])
    messages = load(dir_path, "chat_messages")
    constraints = load(dir_path, "studentconstraint")
    schedules = load(dir_path, "generated_schedules")
    classes = load(dir_path, "schedule_classes")
    ml_rows = checkpoint_run_rows(dir_path)

    print(f"sessions={len(sessions)} messages={len(messages)} constraints={len(constraints)} "
          f"schedules={len(schedules)} classes={len(classes)} ml_runs={len(ml_rows)}")
    if dry_run:
        print(json.dumps(ml_rows, ensure_ascii=False, indent=1))
        return

    manifest = {"chat_sessions": [], "chat_messages": [], "studentconstraint": [],
                "generated_schedules": [], "schedule_classes": [], "ml_criterion_weights": []}
    manifest_path = os.path.join(dir_path, "upload_manifest.json")

    def save_manifest():
        with open(manifest_path, "w", encoding="utf-8") as f:
            json.dump(manifest, f, indent=1)

    try:
        session_map = {}
        for s in sessions:
            row = {k: s[k] for k in ["student_id", "semester", "title", "created_at", "is_pinned"]}
            new_id = insert_one(client, "chat_sessions", row, "session_id")
            session_map[s["session_id"]] = new_id
            manifest["chat_sessions"].append(new_id)
        print(f"✅ chat_sessions: {len(session_map)}")

        msg_rows = [{"session_id": session_map[m["session_id"]], "sender": m["sender"],
                     "message_text": m["message_text"], "created_at": m["created_at"]}
                    for m in sorted(messages, key=lambda r: r["created_at"])]
        manifest["chat_messages"] = insert_many(client, "chat_messages", msg_rows, "message_id")
        print(f"✅ chat_messages: {len(manifest['chat_messages'])}")

        con_rows = [{"student_id": c["student_id"], "session_id": session_map[c["session_id"]],
                     "constraint_type": c["constraint_type"], "constraint_payload": c["constraint_payload"],
                     "importance_level": c["importance_level"], "active": c["active"],
                     "received_at": c["received_at"]} for c in constraints]
        manifest["studentconstraint"] = insert_many(client, "studentconstraint", con_rows, "constraint_id")
        print(f"✅ studentconstraint: {len(manifest['studentconstraint'])}")

        schedule_map = {}
        sched_cols = ["alt_key", "title", "total_courses", "total_hours", "is_selected", "created_at",
                      "score_g", "score_d", "score_ld", "score_t", "score_lw", "score_c", "score_a",
                      "final_score", "penalty", "selection_mark"]
        for g in sorted(schedules, key=lambda r: r["created_at"]):
            row = {k: g.get(k) for k in sched_cols}
            row["session_id"] = session_map[g["session_id"]]
            new_id = insert_one(client, "generated_schedules", row, "schedule_id")
            schedule_map[g["schedule_id"]] = new_id
            manifest["generated_schedules"].append(new_id)
        print(f"✅ generated_schedules: {len(schedule_map)}")

        cls_rows = [{"schedule_id": schedule_map[c["schedule_id"]], "course_name": c["course_name"],
                     "class_type": c["class_type"], "lecturer": c["lecturer"], "day_of_week": c["day_of_week"],
                     "start_time": c["start_time"], "end_time": c["end_time"]} for c in classes]
        manifest["schedule_classes"] = insert_many(client, "schedule_classes", cls_rows, "class_id")
        print(f"✅ schedule_classes: {len(manifest['schedule_classes'])}")

        client.table("ml_criterion_weights").update({"is_best_run": False}).eq("is_best_run", True).execute()
        manifest["ml_criterion_weights"] = insert_many(client, "ml_criterion_weights", ml_rows, "run_id")
        print(f"✅ ml_criterion_weights: {len(manifest['ml_criterion_weights'])}")
    finally:
        save_manifest()
        print(f"📝 Manifest saved: {manifest_path}")


def rollback(client, dir_path):
    manifest_path = os.path.join(dir_path, "upload_manifest.json")
    with open(manifest_path, encoding="utf-8") as f:
        manifest = json.load(f)
    order = [("schedule_classes", "class_id"), ("generated_schedules", "schedule_id"),
             ("studentconstraint", "constraint_id"), ("chat_messages", "message_id"),
             ("chat_sessions", "session_id"), ("ml_criterion_weights", "run_id")]
    for table, pk in order:
        ids = manifest.get(table, [])
        for i in range(0, len(ids), CHUNK):
            client.table(table).delete().in_(pk, ids[i:i + CHUNK]).execute()
        print(f"🗑️ {table}: {len(ids)} removed")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", default=os.path.join(PROJECT_DIR, "simulation_output"))
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--rollback", action="store_true")
    args = ap.parse_args()

    client = create_client(os.getenv("SUPABASE_URL"), os.getenv("SUPABASE_KEY"))
    if args.rollback:
        rollback(client, args.dir)
    else:
        upload(client, args.dir, args.dry_run)
